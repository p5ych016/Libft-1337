#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	long	nb;
	char	s;

	nb = (long) n;
	if (nb < 0)
	{
		ft_putchar_fd('-', fd);
		nb = -nb;
	}
	if (nb >= 10)
	{
		ft_putnbr_fd(nb / 10, fd);
		ft_putnbr_fd(nb % 10, fd);
		return ;
	}
	s = nb + '0';
	ft_putchar_fd(s, fd);
}
